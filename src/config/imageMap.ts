/**
 * Motor de Busca Inteligente: Curadoria + LoremFlickr (Qualquer palavra)
 */
export const findImages = (query: string): string[] => {
  if (!query) return [];
  const q = query.toLowerCase().trim().normalize("NFD").replace(/[\u0300-\u036f]/g, "");

  let results: string[] = [];

  // 1. Tenta encontrar na Biblioteca Premium primeiro
  if (imageDatabase[q]) results = [...imageDatabase[q]];

  // 2. Busca por sinônimos
  Object.entries(synonyms).forEach(([key, list]) => {
    if (list.some(s => s.includes(q) || q.includes(s))) {
      results = [...results, ...(imageDatabase[key] || [])];
    }
  });

  // 3. Fallback: Se não encontrou nada na curadoria, o EditorForm fará a busca via API real do Pixabay
  // Retornamos vazio aqui para evitar poluição de imagens genéricas demais
  return Array.from(new Set(results)).slice(0, 15);
};
